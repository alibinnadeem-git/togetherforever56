-- ForeverPoints tamper-evidence + dispute/refund/correction workflow
create extension if not exists pgcrypto;

alter table app.foreverpoints_ledger
  add column if not exists ledger_sequence bigint generated by default as identity,
  add column if not exists previous_hash text,
  add column if not exists payload_hash text,
  add column if not exists chain_hash text,
  add column if not exists server_signature text,
  add column if not exists integrity_version integer not null default 1;

create unique index if not exists uq_foreverpoints_ledger_sequence on app.foreverpoints_ledger(ledger_sequence);
create unique index if not exists uq_foreverpoints_ledger_chain_hash on app.foreverpoints_ledger(chain_hash) where chain_hash is not null;

create or replace function app.foreverpoints_set_integrity()
returns trigger language plpgsql as $$
declare
  v_prev text;
  v_payload text;
begin
  perform pg_advisory_xact_lock(hashtext('togetherforever:foreverpoints:ledger'));

  select chain_hash into v_prev
  from app.foreverpoints_ledger
  where ledger_sequence < new.ledger_sequence
  order by ledger_sequence desc
  limit 1;

  new.previous_hash := coalesce(v_prev, repeat('0',64));
  v_payload := concat_ws('|',
    new.id::text,
    new.account_id::text,
    new.person_id::text,
    new.transaction_type,
    new.points_delta::text,
    coalesce(new.activity_type,''),
    coalesce(new.source_object_type,''),
    coalesce(new.source_object_id::text,''),
    coalesce(new.rule_id::text,''),
    coalesce(new.related_ledger_id::text,''),
    coalesce(new.idempotency_key,''),
    coalesce(new.description,''),
    coalesce(new.expires_at::text,''),
    coalesce(new.created_by_person_id::text,''),
    new.created_at::text,
    new.integrity_version::text
  );

  new.payload_hash := encode(digest(v_payload,'sha256'),'hex');
  new.chain_hash := encode(digest(new.previous_hash || '|' || new.payload_hash || '|' || coalesce(new.server_signature,''),'sha256'),'hex');
  return new;
end $$;

create or replace function app.foreverpoints_block_mutation()
returns trigger language plpgsql as $$
begin
  raise exception 'ForeverPoints ledger is append-only. Create a reversal/correction transaction instead.' using errcode='55000';
end $$;

drop trigger if exists trg_foreverpoints_integrity on app.foreverpoints_ledger;
create trigger trg_foreverpoints_integrity
before insert on app.foreverpoints_ledger
for each row execute function app.foreverpoints_set_integrity();

drop trigger if exists trg_foreverpoints_immutable_update on app.foreverpoints_ledger;
create trigger trg_foreverpoints_immutable_update
before update on app.foreverpoints_ledger
for each row execute function app.foreverpoints_block_mutation();

drop trigger if exists trg_foreverpoints_immutable_delete on app.foreverpoints_ledger;
create trigger trg_foreverpoints_immutable_delete
before delete on app.foreverpoints_ledger
for each row execute function app.foreverpoints_block_mutation();

