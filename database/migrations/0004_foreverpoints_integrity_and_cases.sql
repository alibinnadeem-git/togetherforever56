create or replace function app.verify_foreverpoints_chain()
returns table(ledger_sequence bigint, stored_hash text, expected_hash text, valid boolean)
language sql stable as $$
with ordered as (
  select l.*,
    lag(chain_hash) over(order by ledger_sequence) as prior_chain
  from app.foreverpoints_ledger l
), calc as (
  select o.ledger_sequence,
         o.chain_hash as stored_hash,
         encode(digest(
           coalesce(o.prior_chain, repeat('0',64)) || '|' || o.payload_hash || '|' || coalesce(o.server_signature,''),
           'sha256'
         ),'hex') as expected_hash
  from ordered o
)
select ledger_sequence, stored_hash, expected_hash, stored_hash = expected_hash
from calc
order by ledger_sequence;
$$;

