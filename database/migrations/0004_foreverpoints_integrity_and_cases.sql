  status text not null default 'submitted' check (status in (
    'submitted','acknowledged','under_review','evidence_requested','awaiting_user','awaiting_admin',
    'awaiting_approver','approved','partially_approved','rejected','corrected','reversed','refunded',
    'closed','reopened','escalated'
  )),
  subject text not null,
  description text not null,
  requested_points bigint,
  resolution_type text check (resolution_type is null or resolution_type in (
    'uphold','reverse','partial_correction','replace','refund','correction_credit','correction_debit',
    'goodwill_credit','waive_recovery','no_change'
  )),
  resolution_notes text,
  assigned_to_person_id uuid references app.persons(id) on delete set null,
  opened_at timestamptz not null default now(),
  resolved_at timestamptz,
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

